// Run: node scripts/check-conf-theme.cjs (no browser, network, or app DB).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/hooks/useTheme.ts'), 'utf8');
function fixture(saved, blocked = false, osDark = false) {
  let effect, cursor = 0, cleanup;
  const states = [];
  const listeners = new Map();
  const media = { matches: osDark, addEventListener: (_, f) => listeners.set('media', f), removeEventListener: () => listeners.delete('media') };
  const element = { dataset: {}, classList: { toggle: (_, value) => element.dark = value } };
  const window = { matchMedia: () => media, addEventListener: (k, f) => listeners.set(k, f), removeEventListener: k => listeners.delete(k), dispatchEvent: e => listeners.get(e.type)?.() };
  const localStorage = { getItem: () => { if (blocked) throw Error('blocked'); return saved; }, setItem: (_, v) => { if (blocked) throw Error('blocked'); saved = v; } };
  const context = { exports: {}, window, document: { documentElement: element }, localStorage, Event: class { constructor(type) { this.type = type; } }, require: () => ({ useEffect: f => effect = f, useState: initial => { const i = cursor++; if (!(i in states)) states[i] = initial; return [states[i], value => states[i] = value]; } }) };
  vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
  const hook = context.exports.useTheme();
  assert.equal(states[0], 'dark', 'initial hydration must match server');
  assert.equal(element.dataset.theme, undefined, 'no render-time DOM mutation');
  cleanup = effect();
  return { hook, element, media, listeners, state: () => states[0], error: () => states[1], saved: () => saved, setSaved: v => saved = v, setBlocked: v => blocked = v, cleanup };
}
for (const saved of [null, 'invalid', 'DARK', 'dark']) assert.equal(fixture(saved).element.dataset.theme, 'dark');
const f = fixture('light');
assert.equal(f.element.dark, false);
f.hook.changeTheme('system');
assert.equal(f.saved(), 'system');
assert.equal(f.element.dataset.theme, 'light');
f.media.matches = true; f.listeners.get('media')();
assert.equal(f.element.dataset.theme, 'dark');
f.hook.changeTheme('light'); f.listeners.get('media')();
assert.equal(f.element.dataset.theme, 'light', 'explicit selection ignores OS');
assert.equal(fixture(f.saved()).element.dataset.theme, 'light', 'fresh hook restores persisted preference');
assert.equal(fixture('system', false, true).element.dataset.theme, 'dark', 'system restores with current OS setting');
f.setSaved('dark'); f.listeners.get('storage')({ key: 'unrelated' });
assert.equal(f.element.dataset.theme, 'light', 'unrelated storage changes do not affect theme');
f.setSaved('light');
f.hook.changeTheme('invalid'); assert.equal(f.saved(), 'light');
f.setSaved('dark'); f.listeners.get('storage')({ key: 'theme' }); assert.equal(f.element.dark, true);
f.setSaved(null); f.listeners.get('storage')({ key: null }); assert.equal(f.state(), 'dark');
f.cleanup(); assert.equal(f.listeners.size, 0);
const blocked = fixture(null, true);
blocked.hook.changeTheme('system'); blocked.media.matches = true; blocked.listeners.get('media')();
assert.equal(blocked.element.dark, true); assert.equal(blocked.state(), 'system');
assert.equal(blocked.error(), true, 'storage denial must expose a session-only warning');
assert.equal(f.error(), false, 'successful persistence clears theme warning');
assert.match(fs.readFileSync(path.join(root, 'src/app/(panel)/profile/page.tsx'), 'utf8'), /themeError && <p role="alert"/, 'theme failure is shown beside appearance controls');
blocked.hook.changeTheme('light'); assert.equal(blocked.element.dark, false);
assert.equal(blocked.error(), true);
blocked.setBlocked(false); blocked.hook.changeTheme('light');
assert.equal(blocked.saved(), 'light'); assert.equal(blocked.error(), false, 'retry saves and clears session-only warning');
const config = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root, 'tailwind.config.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText, { exports: config, require });
assert.equal(config.default.theme.extend.colors.brand[600], '#4f46e5');
assert.match(config.default.theme.extend.backgroundColor.gray[950], /--surface-page/);
assert.match(config.default.theme.extend.textColor.white, /--text-strong/);
assert.equal(config.default.theme.extend.colors.red, undefined, 'status backgrounds stay native');
assert.match(config.default.theme.extend.textColor.violet[400], /--ink-purple/, 'light violet shares existing accessible purple ink');
assert.equal(config.default.theme.extend.backgroundColor.emerald[600], '#047857', 'solid emerald action uses 700 contrast');
const profile = fs.readFileSync(path.join(root, 'src/app/(panel)/profile/page.tsx'), 'utf8');
assert.match(profile, /aria-label="Quick unlock passcode"/);
assert.match(profile, /relative flex h-11 w-12/, 'switch touch target is 44px');
console.log('CONF theme: hydration, validation, persistence, OS changes, storage denial/events, cleanup, semantic tokens PASS');
