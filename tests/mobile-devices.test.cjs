const assert=require("node:assert/strict");
const path=require("node:path");
assert.match(process.env.DATABASE_URL||"", /^file:\/tmp\/vps-mobile-ci-[^/]+\/fixture\.db$/);
const root=path.resolve(__dirname,"../scripts/monitoring-runtime/lib");
const {prisma}=require(path.join(root,"db.js"));
const {issueMobilePairing,redeemMobilePairing,authorizeMobileBearer,revokeMobileDevice,listMobileDevices}=require(path.join(root,"mobile-devices.js"));
const rejects=(fn,status)=>assert.rejects(fn,e=>e.status===status);
(async()=>{
 const a=await prisma.server.create({data:{name:"Allowed",host:"example.invalid",username:"mock"}});
 const b=await prisma.server.create({data:{name:"Forbidden",host:"example.invalid",username:"mock"}});
 const user=await prisma.user.create({data:{username:"mobile-test-viewer",passwordHash:"fixture-only",role:"VIEWER",serverAccessMode:"SELECTED",serverAccess:{create:{serverId:a.id}}}});
 const other=await prisma.user.create({data:{username:"mobile-test-other",passwordHash:"fixture-only",role:"OWNER"}});
 const issue=(ids=[a.id])=>issueMobilePairing(user.id,0,"Demo phone",ids);
 await rejects(()=>issue([b.id]),403);
 await rejects(()=>issue(["local"]),403);
 const p=await issue();
 const saved=await prisma.mobileDevice.findUnique({where:{id:p.id}});
 assert.notEqual(saved.pairingHash,p.code);
 assert.equal(saved.tokenHash,null);
 const race=await Promise.allSettled([redeemMobilePairing(p.code),redeemMobilePairing(p.code)]);
 assert.equal(race.filter(x=>x.status==="fulfilled").length,1);
 const token=race.find(x=>x.status==="fulfilled").value.token;
 const bearer="Bearer "+token;
 await rejects(()=>redeemMobilePairing(p.code),401);
 const credential=await prisma.mobileDevice.findUnique({where:{id:p.id}});
 assert.notEqual(credential.tokenHash,token);
 assert.equal(credential.pairingHash,null);
 assert.deepEqual((await authorizeMobileBearer(bearer)).serverIds,[a.id]);
 await rejects(()=>authorizeMobileBearer("Bearer invalid"),401);
 assert.equal(JSON.stringify(await listMobileDevices(user.id)).includes(token),false);
 assert.equal((await listMobileDevices(other.id)).devices.length,0);
 await rejects(()=>revokeMobileDevice(other.id,p.id,0),404);
 await prisma.userServerAccess.deleteMany({where:{userId:user.id}});
 await rejects(()=>authorizeMobileBearer(bearer),401);
 await prisma.userServerAccess.create({data:{userId:user.id,serverId:a.id}});
 await revokeMobileDevice(user.id,p.id,0);
 await rejects(()=>authorizeMobileBearer(bearer),401);
 const expired=await issue();
 await prisma.mobileDevice.update({where:{id:expired.id},data:{pairingExpiresAt:new Date(0)}});
 await rejects(()=>redeemMobilePairing(expired.code),401);
 const fresh=await issue();const paired=await redeemMobilePairing(fresh.code);
 await prisma.user.update({where:{id:user.id},data:{isActive:false}});
 await rejects(()=>authorizeMobileBearer("Bearer "+paired.token),401);
 await prisma.user.update({where:{id:user.id},data:{isActive:true,passwordHash:"changed-fixture"}});
 await rejects(()=>authorizeMobileBearer("Bearer "+paired.token),401);
 const afterPassword=await issue();const session=await redeemMobilePairing(afterPassword.code);
 await prisma.appSetting.upsert({where:{key:"security"},create:{key:"security",value:JSON.stringify({forceLogoutVersion:1})},update:{value:JSON.stringify({forceLogoutVersion:1})}});
 await rejects(()=>authorizeMobileBearer("Bearer "+session.token),401);
 await rejects(()=>issue(),401);
 const audits=await prisma.auditLog.findMany({where:{userId:user.id}});
 assert.equal(JSON.stringify(audits).includes(token),false);
 assert.equal(JSON.stringify(audits).includes(p.code),false);
 console.log("Mobile pairing, replay, scope, revoke and session invalidation: PASS");
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>prisma.$disconnect());
