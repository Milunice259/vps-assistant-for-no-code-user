import assert from "node:assert/strict";
import { percent, projectMobileObservation as project } from "../src/lib/mobile-snapshot-view.ts";
const now = 1_800_000_000_000;
const worker = {enabled:true,online:true,intervalSeconds:60};
const obs = {observedAt:now-1000,reachability:"online",cpuPercent:0,memoryPercent:62,diskPercent:100};
assert.equal(project(true,obs,worker,now).state,"online");
assert.equal(project(true,obs,worker,now).cpuPercent,0);
assert.equal(project(false,obs,worker,now).state,"disabled");
assert.equal(project(false,obs,worker,now).memoryPercent,null);
assert.equal(project(true,null,worker,now).state,"unknown");
assert.equal(project(true,{...obs,reachability:"unknown"},worker,now).memoryPercent,null);
assert.equal(project(true,{...obs,reachability:"offline"},worker,now).state,"offline");
assert.equal(project(true,{...obs,observedAt:now-186000},worker,now).state,"stale");
assert.equal(project(true,{...obs,observedAt:now+1},worker,now).state,"unknown");
assert.equal(project(true,obs,{...worker,online:false},now).state,"stale");
assert.equal(project(true,obs,{...worker,enabled:false},now).diskPercent,null);
assert.equal(project(true,{...obs,cpuPercent:101},worker,now).cpuPercent,null);
for (const v of [null,undefined,"50",NaN,Infinity,-1,101]) assert.equal(percent(v),null);
assert.equal(percent(0),0); assert.equal(percent(100),100);
console.log("Mobile snapshot projection: PASS");
